"""Auto-generate a PR description from the agent's trajectory."""

from __future__ import annotations

from app.agent.trajectory import Trajectory
from app.agent.types import AgentStatus


def build_pr_description(
    *,
    issue_number: int,
    issue_title: str,
    trajectory: Trajectory,
    status: AgentStatus,
    baseline_tests: dict | None,
    final_tests: dict | None,
    model: str,
    duration_ms: int,
    dashboard_url: str,
    run_id: str,
    root_cause_override: str | None = None,
    modified_files: list[str] | None = None,
    total_steps: int | None = None,
) -> str:
    steps = trajectory.steps
    edited = sorted(
        {
            s.action.args.get("path")
            for s in steps
            if s.action and s.action.tool in ("edit_file", "create_file") and s.action.args.get("path")
        }
    )
    root_cause = root_cause_override or _infer_root_cause(trajectory)

    edited = modified_files or edited
    changes = "\n".join(f"- Modified `{p}`" for p in edited) or "- (no file changes recorded)"
    final = final_tests or {}
    base = baseline_tests or {}
    test_line = (
        f"{final.get('passed', '?')} passing / {final.get('failed', '?')} failing"
        if final
        else "not recorded"
    )
    duration_s = round(duration_ms / 1000, 1)
    step_count = total_steps if total_steps is not None else len(steps)

    key_decisions = _key_decisions(trajectory)

    return f"""## NeuraSWE Fix for #{issue_number}

### Issue
{issue_title}

### Root Cause
{root_cause}

### Changes Made
{changes}

### Operational Trace
The agent completed {step_count} steps. Private model reasoning is not published. Key operations:
{key_decisions}

[View validation and operational evidence →]({dashboard_url}/runs/{run_id})

### Test Results
- Baseline: {base.get('passed', '?')} passing / {base.get('failed', '?')} failing
- After fix: {test_line}

---
_Generated by NeuraSWE using {model} • {step_count} steps • {duration_s}s • status: {status.value}_
"""


def _infer_root_cause(trajectory: Trajectory) -> str:
    return "No structured root-cause summary was provided."


def _key_decisions(trajectory: Trajectory, limit: int = 5) -> str:
    lines = []
    n = 1
    for s in trajectory.steps:
        if not s.action:
            continue
        if s.action.tool in ("search_code", "edit_file", "create_file", "run_tests", "submit_solution"):
            lines.append(f"{n}. `{s.action.tool}` completed")
            n += 1
        if len(lines) >= limit:
            break
    return "\n".join(lines) or "1. See full trace."
